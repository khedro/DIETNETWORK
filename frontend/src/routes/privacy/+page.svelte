<h1>Privacy &amp; data retention</h1>

<div class="stack">
	<div class="card">
		<h3>What we collect</h3>
		<p class="muted">
			Your account email, and the genotype file (VCF or bgen) you choose to upload for ancestry
			inference, plus the derived ancestry predictions.
		</p>
	</div>
	<div class="card">
		<h3>Why</h3>
		<p class="muted">
			Solely to run the Diet Network ancestry inference model on your behalf and show you the
			results. We do not use your data for any other purpose, and we do not sell or share it.
		</p>
	</div>
	<div class="card">
		<h3>Where it is stored</h3>
		<p class="muted">
			On encrypted storage within Canadian research-cloud infrastructure (Arbutus / Digital
			Research Alliance of Canada). All processing happens in Canada.
		</p>
	</div>
	<div class="card">
		<h3>Retention</h3>
		<p class="muted">
			Your raw uploaded genotype file is deleted immediately once inference completes
			successfully — it is the most sensitive artifact and is not needed after predictions exist.
			Derived results (predictions and SNP-overlap counts) are kept for <strong>30 days</strong>
			from upload, then permanently deleted by an automated daily job. You can also request earlier
			deletion.
		</p>
	</div>
	<div class="card">
		<h3>Your rights</h3>
		<p class="muted">
			You may only ever access your own uploads and results. Under Quebec's Law 25 and PIPEDA,
			you may request access to, correction of, or deletion of your personal information at any
			time by contacting the platform operator.
		</p>
	</div>
</div>
